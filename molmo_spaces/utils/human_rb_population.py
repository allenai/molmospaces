"""Scatter humanoid avatars (scene population / soft obstacles) around any scene.

Used by BaseMujocoTaskSampler when task_sampler_config.num_humans > 0, so every
task type can be populated with humans: avatars are attached to the MjSpec
before compilation (add_humans_to_scene) and placed at random free points of the
occupancy map after each task is sampled (place_humans).

Avatars are generated by scripts/assets/convert_human_rb.py from the Microsoft
Rocketbox avatar library into ROBOTS_DIR, or installed there from the shared
asset store, and registered from there as a user asset library (see
HumanRBVariant.is_downloadable, and that script's docstring for setup). Three
variants, selected by BaseMujocoTaskSamplerConfig.human_variant (see
HumanRBVariant): articulated ragdolls (default), the same ragdolls skinned, or
static mannequins. All three ship exactly one top-level body per avatar MJCF, so
staging/placement below doesn't need to know which variant is in use -- apart
from the skins' own namespacing, see utils.mujoco_scene_utils.namespace_skins.
"""

import json
import logging

import mujoco
import numpy as np
from mujoco import MjSpec

from molmo_spaces.configs.task_sampler_configs import BaseMujocoTaskSamplerConfig, HumanRBVariant
from molmo_spaces.env.env import CPUMujocoEnv
from molmo_spaces.molmo_spaces_constants import USER_ASSET_LIBRARIES
from molmo_spaces.robots.human_rb import human_rb_library_dir
from molmo_spaces.tasks.task_sampler_errors import ObjectPlacementError
from molmo_spaces.utils.lazy_loading_utils import install_uid
from molmo_spaces.utils.mujoco_scene_utils import namespace_skins, place_object_near

log = logging.getLogger(__name__)

_HUMAN_RB_STAGING_CENTER = np.array([5.0, -5.0, 25.0])  # distinct from pickupables' [5, 5, 25]


_CONVERT_COMMAND = {
    HumanRBVariant.ARTICULATED: "articulate",
    HumanRBVariant.SKINNED: "skin",
    HumanRBVariant.STATIC: "convert",
}


def ensure_human_rb_library_registered(variant: HumanRBVariant) -> None:
    """Make `variant`'s library resolvable by install_uid, downloading it if published.

    The published builds install on demand (human_rb_library_dir); the static one
    has to have been generated locally, so its absence is a setup problem worth
    saying out loud rather than an install failure.
    """
    library_name = str(variant)
    if library_name in USER_ASSET_LIBRARIES:
        return
    avatars_dir = human_rb_library_dir(variant)
    if not (avatars_dir / "assets_index.json").exists():
        raise RuntimeError(
            f"No humanoid assets found at {avatars_dir}. Generate them first with "
            f"scripts/assets/convert_human_rb.py {_CONVERT_COMMAND[variant]} --all "
            "(see its docstring for setup)."
        )
    from molmo_spaces.molmo_spaces_constants import register_user_asset_library

    register_user_asset_library(library_name, avatars_dir)


def _discover_human_rb_uids(variant: HumanRBVariant) -> list[str]:
    index_path = human_rb_library_dir(variant) / "assets_index.json"
    return sorted(json.loads(index_path.read_text()).keys())


def add_humans_to_scene(spec: MjSpec, config: BaseMujocoTaskSamplerConfig) -> list[str]:
    """Attach config.num_humans randomly chosen avatars to `spec`, staged off-scene.

    Returns the top-level body names of the attached avatars, for place_humans.
    """
    pool = config.human_uids or _discover_human_rb_uids(config.human_variant)
    if not pool:
        raise ValueError("No human UIDs available (pool is empty)")

    num_humans = config.num_humans
    replace = len(pool) < num_humans
    selected_uids = list(np.random.choice(pool, size=num_humans, replace=replace))

    human_names = []
    for i, uid in enumerate(selected_uids):
        avatar_xml = install_uid(uid)
        avatar_spec = MjSpec.from_file(str(avatar_xml))
        if len(avatar_spec.worldbody.bodies) != 1:
            log.warning(f"{avatar_xml} has {len(avatar_spec.worldbody.bodies)} bodies, expected 1.")
        avatar_body = avatar_spec.worldbody.bodies[0]

        # Stage off-scene in a grid, same pattern as PickTaskSampler's own
        # added-pickupables staging (_add_pickupables_to_scene) but at a
        # distinct location so the two staging areas don't overlap. No
        # reorientation quat here (unlike pickupables' own +90deg-about-X,
        # which corrects for Objaverse's axis convention) -- avatars are
        # already authored Z-up, standing, by convert_human_rb.py.
        position = _HUMAN_RB_STAGING_CENTER + np.array([i, 0.0, 0.0])
        attach_frame = spec.worldbody.add_frame(pos=position)
        # Namespace must match the "{idx}_{idx}" two-part pattern
        # PickTaskSampler._get_scene_objects (pick_task_sampler.py) uses to
        # recognize and skip already-added objects when scanning for pickup
        # candidates -- same convention _add_pickupables_to_scene uses
        # (f"{namespace}{i}_{j}/"), just with a fixed second index since
        # avatars have no multiplier dimension.
        namespace = f"{config.human_namespace}{i}_0/"
        original_body_name = avatar_body.name
        # Only the skinned variant has any skins; a no-op for the other two.
        namespace_skins(avatar_spec, namespace)
        attach_frame.attach_body(avatar_body, namespace, "")

        human_names.append(namespace + original_body_name)

    log.info(f"Added {len(human_names)} humans to scene: {selected_uids}")
    return human_names


def place_humans(
    env: CPUMujocoEnv,
    human_names: list[str],
    config: BaseMujocoTaskSamplerConfig,
    exclude_xy: list[np.ndarray],
) -> None:
    """Move the staged avatars to random free points of the scene's occupancy map,
    keeping config.human_min_spacing from each other and from `exclude_xy`."""
    if not human_names:
        return

    om = env.object_managers[env.current_batch_index]
    data = env.current_data

    thormap = env.get_thormap(agent_radius=config.human_agent_radius)
    free_points = thormap.get_free_points()[:, :2]

    min_spacing = config.human_min_spacing
    rng = np.random.default_rng()
    shuffled = free_points[rng.permutation(len(free_points))]

    # A candidate that's spatially "free" per the dilated occupancy map can still
    # fail place_object_near's real contact check (the map dilation is an
    # approximation, not an exact clearance guarantee) -- so each avatar gets its
    # own retry budget across *different* candidates, and `next_idx` advances
    # monotonically across avatars so a point already tried (successfully or not)
    # is never reconsidered for a later avatar.
    accepted_points: list[np.ndarray] = []
    next_idx = 0
    placed = 0
    for name in human_names:
        avatar_id = om.get_object_body_id(name)
        attempts = 0
        placed_this_avatar = False
        while attempts < config.max_human_point_attempts and next_idx < len(shuffled):
            candidate = shuffled[next_idx]
            next_idx += 1
            too_close = any(
                np.linalg.norm(candidate - other) < min_spacing
                for other in accepted_points + exclude_xy
            )
            if too_close:
                continue
            attempts += 1
            point_3d = np.array([candidate[0], candidate[1], 0.02])
            try:
                place_object_near(
                    data=data,
                    object_id=avatar_id,
                    placement_point=point_3d,
                    min_dist=0.0,
                    max_dist=config.human_placement_radius,
                )
            except (ObjectPlacementError, ValueError):
                continue
            accepted_points.append(candidate)
            placed += 1
            placed_this_avatar = True
            break

        if not placed_this_avatar:
            log.info(f"[Humans] Could not place {name} after {attempts} attempts")

    mujoco.mj_forward(env.current_model, data)
    log.info(f"[Humans] Placed {placed}/{len(human_names)} humans")
